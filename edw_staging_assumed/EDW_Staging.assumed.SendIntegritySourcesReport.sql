-- Database: EDW_Staging
-- Schema: assumed
-- Procedure: SendIntegritySourcesReport

CREATE PROCEDURE assumed.SendIntegritySourcesReport
--DECLARE
	@OverrideRecipients NVARCHAR(MAX) = NULL
AS
BEGIN TRY
	-----------------------------------------------------------------------
    --#Parameters - define parameters
	-----------------------------------------------------------------------
    DROP TABLE IF EXISTS #Parameters
    SELECT
        ProcessName				= ISNULL(OBJECT_SCHEMA_NAME(@@PROCID) + '.' + OBJECT_NAME(@@PROCID), 'assumed.SendIntegritySourcesReport'),
		Curr_ProcessStartDate	= SYSDATETIME(),
		SenderProfile			= erc.SenderProfile,
        ServerName				= erc.EnvironmentName,
        Recipients				= ISNULL(@OverrideRecipients, erc.Recipients),
		------
        ReportDate				= CONVERT(DATETIME, NULL),
		RowsCnt					= CONVERT(INT, 0),
		IntegrityCheckResult	= CONVERT(INT, 0)
    INTO #Parameters
	FROM EDW_Staging.assumed.EmailReportConfiguration erc
	WHERE erc.ReportName = 'Integrity Sources Report'

	IF NOT EXISTS (SELECT 1 FROM #Parameters)
	BEGIN
		;THROW 50000, 'Missing email configuration', 10
	END

	-------------------------------------------------------------------------
    DROP TABLE IF EXISTS #ReportData
	SELECT Table_Name		= ISNULL(TableName, 'Unknown')
		 , Rows_Count		= ISNULL(EntryCount, 'Unknown')
		 , Integrity_Ok		= ISNULL(IntegrityOk, 'Unknown')
    INTO #ReportData
    FROM EDW_Staging.assumed.SourceIntegrityCheck
   WHERE EndDate ='9999-12-31'

	-------------------------------------------------------------------------
    UPDATE #Parameters
    SET ReportDate				= (SELECT ISNULL(Curr_ProcessStartDate, GETDATE()) FROM #Parameters ),
		RowsCnt					= (SELECT COUNT(*) FROM #ReportData ),
		IntegrityCheckResult	= (SELECT EDW_Staging.assumed.Get_IntegritySourceSetCheck())
 
	-------------------------------------------------------------------------
	-- collect table data
	-------------------------------------------------------------------------
    DECLARE @xmlData XML = (SELECT Table_Name, Rows_Count, Integrity_Ok
							  FROM #ReportData AS Record
							 ORDER BY
								   Table_Name, Rows_Count, Integrity_Ok
							FOR XML auto, elements XSINIL	)
	-------------------------------------------------------------------------
    DECLARE @htmlTable NVARCHAR(MAX);
		SET @htmlTable = N'<table  border=''1'' style=''border-collapse:collapse;font-size:12px''><tr>';

    -- add table headers
	SELECT @htmlTable = @htmlTable + N'<th style="min-width:40">' + REPLACE(a.value('local-name(.)', 'NVARCHAR(MAX)'), '_', ' ') + N'</th>'
      FROM @xmlData.nodes('/Record[1]/*') AS t(a);

	   SET @htmlTable = @htmlTable + N'</tr>' + CHAR(13) + CHAR(10);

    -- add table rows
    SELECT @htmlTable = @htmlTable + N'<tr>' + (
												SELECT '<td style="min-width:40;font-size:12px">' + ISNULL(t.c.value('.', 'NVARCHAR(MAX)'), '') + '</td>' AS [td]
												FROM a.nodes('*') AS t(c)
												FOR XML PATH(''),
													TYPE
												).value('.', 'NVARCHAR(MAX)') + N'</tr>' + CHAR(13) + CHAR(10)
     FROM @xmlData.nodes('/Record') AS t(a);

	  SET @htmlTable = @htmlTable + N'</table>'
	-------------------------------------------------------------------------
    -- Compose message
	-------------------------------------------------------------------------
    DECLARE @Subj		NVARCHAR(MAX)
    DECLARE @Header		NVARCHAR(MAX)
    DECLARE @Subheader	NVARCHAR(MAX)
    DECLARE @Footer		NVARCHAR(MAX)
    DECLARE @Recipients NVARCHAR(MAX)
	DECLARE @ProfileName SYSNAME

    SELECT
		@Subj		= FORMATMESSAGE('%s Integrity source tables alert %s (%s)', ServerName, CONVERT(VARCHAR, ReportDate, 23), IIF(IntegrityCheckResult=1,'SUCCESSFUL', 'FAILED')),
        @Header		= FORMATMESSAGE('<p>%s Integrity source tables alert %s</p>', ServerName, CONVERT(VARCHAR, ReportDate, 23)),
		@Subheader	= IIF(IntegrityCheckResult=1
						,FORMATMESSAGE('<p><span style="font-weight:bold;color:green">Note: Integrity source tables checking result is SUCCESSFUL</p>')
						,FORMATMESSAGE('<p><span style="font-weight:bold;color:red">Note: Integrity source tables checking result has FAILED</p>') ),
		@Footer		= FORMATMESSAGE('<br><br><span style="font-size:12px;font-style:italic;color:#827a78">This email was sent using an unmonitored mailbox from %s environment. Please do not reply to this email.<br>generated by <b>%s</b></span><br><br>Thank You,<br><b>EDW Team</b>', ServerName, ProcessName),
        @Recipients = Recipients,
		@ProfileName= SenderProfile
    FROM #Parameters

    DECLARE @body NVARCHAR(MAX) = CONCAT ('<html><head><style></style></head><body>',
											@Header,
											@Subheader,
											@HtmlTable,
											@Footer,
											'</body></html>' )

	-------------------------------------------------------------------------
    -- Send email when IntegrityCheckResult is FAILED
	-------------------------------------------------------------------------
    IF EXISTS (SELECT * FROM #Parameters where IntegrityCheckResult=0)
	BEGIN
		EXEC msdb.dbo.sp_send_dbmail 
			@profile_name	= @ProfileName,
			@body			= @Body,
			@Recipients		= @Recipients,
			@subject		= @Subj,
			@body_format	= 'HTML',
			@file_attachments = NULL
	END
	-------------------------------------------------------------------------
    DECLARE @ProcessName		VARCHAR(100)= OBJECT_SCHEMA_NAME(@@PROCID) + '.' + OBJECT_NAME(@@PROCID)
    DECLARE @RowsProcessed		BIGINT		= (SELECT RowsCnt FROM #Parameters)
    DECLARE @LastIdentity		BIGINT		= SCOPE_IDENTITY()
    DECLARE @ProcessingStarted	DATETIME	= (SELECT Curr_ProcessStartDate FROM #Parameters)
    DECLARE @ProcessingEnded	DATETIME	= GETDATE()
    DECLARE @SourceDataDate		DATETIME	= (SELECT [sql_date] FROM ETL.dbo.[day] WHERE today = 1)

    EXEC ETL.dbo.update_etl_controller 
		@ps_process_name			= @ProcessName,
        @pn_rows_processed			= @RowsProcessed,
        @pdt_data_datetime			= @SourceDataDate,
        @pdt_process_start_datetime = @ProcessingStarted,
        @pdt_process_end_datetime	= @ProcessingEnded,
        @pn_error_number			= 0,
        @ps_comment					= NULL,
        @pn_max_processed_event_id	= @LastIdentity
END TRY

BEGIN CATCH
    IF @@TRANCOUNT > 0
    BEGIN
        ROLLBACK
    END

    DECLARE @ErrorDescription VARCHAR(800) = LEFT(CONCAT (
            'Error: ', ERROR_NUMBER(),
            ' - ',
            ERROR_MESSAGE(),
            '; ',
            'Occurred in procedure: ' + ERROR_PROCEDURE() + ', ',
            'Line ',
            ERROR_LINE()
        ),800)
    DECLARE @ErrorNumber		INT = ERROR_NUMBER()
    DECLARE @ErrorMessage		VARCHAR(800) = ERROR_MESSAGE()
    DECLARE @ErrorSeverity		INT = ERROR_SEVERITY()
    DECLARE @ErrorState			INT = ERROR_STATE()
    DECLARE @ProcessNameC		VARCHAR(100) = ISNULL(OBJECT_SCHEMA_NAME(@@PROCID) + '.' + OBJECT_NAME(@@PROCID), 'test')
    DECLARE @ProcessingStartedC DATETIME = (SELECT p.Curr_ProcessStartDate FROM #Parameters p )
    DECLARE @ProcessingEndedC	DATETIME = GETDATE()
    DECLARE @SourceDataDateC	DATETIME = (SELECT [sql_date] FROM ETL.dbo.[day]WHERE today = 1 )

    EXEC ETL.dbo.update_etl_controller 
		@ps_process_name			= @ProcessNameC,
        @pn_rows_processed			= 0,
        @pdt_data_datetime			= @SourceDataDateC,
        @pdt_process_start_datetime = @ProcessingStartedC,
        @pdt_process_end_datetime	= @ProcessingEndedC,
        @pn_error_number			= @ErrorNumber,
        @ps_comment					= @ErrorDescription,
        @pn_max_processed_event_id	= 0

    EXEC ETL.dbo.insert_error_log 
		@process_name	= @ProcessNameC,
        @object_name	= 0,
        @user_message	= @ErrorDescription,
        @status			= 0,
        @remedy			= 'Contact EDW team'

    -- do not raise error at this point
    PRINT @ErrorDescription
        --RAISERROR (@ErrorMessage, @ErrorSeverity, @ErrorState)
END CATCH
