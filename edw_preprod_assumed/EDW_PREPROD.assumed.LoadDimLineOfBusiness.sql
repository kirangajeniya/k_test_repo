-- Database: EDW_PREPROD
-- Schema: assumed
-- Procedure: LoadDimLineOfBusiness

CREATE   PROCEDURE assumed.LoadDimLineOfBusiness
AS
BEGIN
	BEGIN TRY
		DROP TABLE IF EXISTS #Parameters

		SELECT ClosingEndDate = DATEADD(NANOSECOND, -100, SYSDATETIME())
			,NewStartDate = SYSDATETIME()
		INTO #Parameters

		-- Staging logic
		
		DROP TABLE IF EXISTS #DimLineOfBusiness
		
		SELECT DISTINCT LineOfBusinessName = 'Uncoded'
			,solvency_II_regulatory_key = NULL
		INTO #DimLineOfBusiness
		UNION ALL (
		-- manual entries covering cases found in historic data, but no longer generated by the code
		SELECT x.LineOfBusinessName
			,x.solvency_II_regulatory_key
		FROM (
			VALUES('Reinsurance/General', 2846)
			) x (LineOfBusinessName, solvency_II_regulatory_key)
		UNION
		SELECT DISTINCT LineOfBusinessName = NULLIF(TRIM(lob.desc_txt), '') COLLATE DATABASE_DEFAULT
			,solvency_II_regulatory_key = solII.solvency_II_regulatory_key
		FROM src_tirs_db.dbo.acct_byline ab
		INNER JOIN SRC_TIRS_DB.dbo.acct_doc ad
			ON ab.doc_key = ad.doc_key
			AND ad.status_flg = 'P'
		INNER JOIN SRC_TIRS_DB.dbo.trty_master tm
			ON tm.trty_key = ad.trty_key
		INNER JOIN SRC_TIRS_DB.dbo.xrf_lob_cds lob
			ON lob.lob_cd = ab.pr_cls_cd
		INNER JOIN SRC_TIRS_DB.dbo.xrf_annl_stmt_line aslob
			ON lob.annl_stmt_key = aslob.annl_stmt_key
		INNER JOIN SRC_TIRS_DB.dbo.xrf_rpt_ofc xr
			ON XR.rpt_ofc_cd = tm.rpt_ofc_cd
		INNER JOIN SRC_TIRS_DB.dbo.xrf_sub_dept_cds sd
			ON tm.sub_dept_key = sd.sub_dept_key
		LEFT JOIN EDW_PREPROD.dbo.solvency_II_regulatory_etl solII
			ON solII.source = 'TIRS'
				AND solII.assumed_or_direct = 'Assumed'
				AND COALESCE(solII.branch_name, '') COLLATE DATABASE_DEFAULT = COALESCE(XR.rpt_ofc_nm, '')
				AND COALESCE(solII.product_group_name, '') COLLATE DATABASE_DEFAULT = COALESCE(sd.division_nm, '')
				AND COALESCE(solII.product_department_name, '') COLLATE DATABASE_DEFAULT = COALESCE(sd.dept_nm, '')
				AND COALESCE(solII.sub_product, '') COLLATE DATABASE_DEFAULT = COALESCE(Sd.sub_dept_nm, '')
				AND COALESCE(solII.lob_name, '') COLLATE DATABASE_DEFAULT = COALESCE(lob.desc_txt, '')
				AND COALESCE(solII.prorata_or_xol, '') COLLATE DATABASE_DEFAULT = COALESCE(CASE WHEN TM.pro_xol_flg = 'X' THEN 'XOL' ELSE 'Pro Rata' END, '')
				AND COALESCE(solII.treaty_or_fav, '') COLLATE DATABASE_DEFAULT = COALESCE(CASE WHEN TM.trty_or_fac_flg = 'F' THEN 'FAC' ELSE 'Treaty' END, '')
				AND COALESCE(solII.property_or_casualty, '') COLLATE DATABASE_DEFAULT = COALESCE(CASE
				WHEN sd.division_nm LIKE '%property%'
					THEN 'PROPERTY'
				WHEN sd.division_nm LIKE '%marine%'
					THEN 'PROPERTY'
				ELSE 'CASUALTY'
				END, '')
				AND COALESCE(solII.is_lloyds, '') COLLATE DATABASE_DEFAULT = COALESCE(CASE WHEN XR.rpt_ofc_nm LIKE '%lloyd%' THEN 'Lloyds' ELSE 'Non-Lloyds' END, '')
				AND COALESCE(solII.transaction_ASLOB_code, '') COLLATE DATABASE_DEFAULT = COALESCE(aslob.annl_stmt_ln, '')
				AND COALESCE(solII.InceptionFrom, tm.inception_dt, '1 Jan 1900') <= COALESCE(tm.inception_dt, '1 Jan 1900')
				AND COALESCE(solII.InceptionTo, tm.inception_dt, '1 Jan 1900') >= COALESCE(tm.inception_dt, '1 Jan 1900')
		UNION
		SELECT DISTINCT LineOfBusinessName = NULLIF(TRIM(lob.desc_txt), '') COLLATE DATABASE_DEFAULT
			,solvency_II_regulatory_key = solII.solvency_II_regulatory_key
		FROM SRC_TIRS_DB.dbo.claim c
		INNER JOIN SRC_TIRS_DB.dbo.trty_master tm
			ON tm.trty_key = c.trty_key
		LEFT JOIN SRC_TIRS_DB.dbo.xrf_lob_cds lob
			ON lob.lob_cd = c.lob_key
		LEFT JOIN SRC_TIRS_DB.dbo.xrf_annl_stmt_line aslob
			ON lob.annl_stmt_key = aslob.annl_stmt_key
		LEFT JOIN SRC_TIRS_DB.dbo.xrf_rpt_ofc xr
			ON xr.rpt_ofc_cd = tm.rpt_ofc_cd
		LEFT JOIN SRC_TIRS_DB.dbo.xrf_sub_dept_cds sd
			ON tm.sub_dept_key = sd.sub_dept_key
		LEFT JOIN EDW_PREPROD.dbo.solvency_II_regulatory_etl solII
			ON solII.source = 'TIRS'
				AND solII.assumed_or_direct = 'Assumed'
				AND COALESCE(solII.branch_name, '') COLLATE DATABASE_DEFAULT = COALESCE(xr.rpt_ofc_nm, '')
				AND COALESCE(solII.product_group_name, '') COLLATE DATABASE_DEFAULT = COALESCE(sd.division_nm, '')
				AND COALESCE(solII.product_department_name, '') COLLATE DATABASE_DEFAULT = COALESCE(sd.dept_nm, '')
				AND COALESCE(solII.sub_product, '') COLLATE DATABASE_DEFAULT = COALESCE(sd.sub_dept_nm, '')
				AND COALESCE(solII.lob_name, '') COLLATE DATABASE_DEFAULT = COALESCE(lob.desc_txt, '')
				AND COALESCE(solII.prorata_or_xol, '') COLLATE DATABASE_DEFAULT = COALESCE(CASE WHEN tm.pro_xol_flg = 'X' THEN 'XOL' ELSE 'Pro Rata' END, '')
				AND COALESCE(solII.treaty_or_fav, '') COLLATE DATABASE_DEFAULT = COALESCE(CASE WHEN tm.trty_or_fac_flg = 'F' THEN 'FAC' ELSE 'Treaty' END, '')
				AND COALESCE(solII.property_or_casualty, '') COLLATE DATABASE_DEFAULT = COALESCE(CASE WHEN sd.division_nm LIKE '%property%' THEN 'PROPERTY' WHEN sd.division_nm LIKE '%marine%' THEN 'PROPERTY' ELSE 'CASUALTY' END, '')
				AND COALESCE(solII.is_lloyds, '') COLLATE DATABASE_DEFAULT = COALESCE(CASE WHEN xr.rpt_ofc_nm LIKE '%lloyd%' THEN 'Lloyds' ELSE 'Non-Lloyds' END, '')
				AND COALESCE(solII.transaction_ASLOB_code, '') COLLATE DATABASE_DEFAULT = COALESCE(aslob.annl_stmt_ln, '')
				AND COALESCE(solII.InceptionFrom, tm.inception_dt, '1 Jan 1900') <= COALESCE(tm.inception_dt, '1 Jan 1900')
				AND COALESCE(solII.InceptionTo, tm.inception_dt, '1 Jan 1900') >= COALESCE(tm.inception_dt, '1 Jan 1900')
		UNION
		SELECT DISTINCT LineOfBusinessName = t.lob_name
			,solvency_II_regulatory_key = t.solvency_II_regulatory_key
		FROM EDW_PREPROD.dbo.RS_TIRS_CLAIMS_TOPSIDE t
		UNION
		SELECT DISTINCT LineOfBusinessName = t.lob_name
			,solvency_II_regulatory_key = t.solvency_II_regulatory_key
		FROM EDW_PREPROD.dbo.RS_TIRS_UNDERWRITING_TOPSIDE t
		UNION
		SELECT DISTINCT LineOfBusinessName = t.lob_name COLLATE DATABASE_DEFAULT
			,solvency_II_regulatory_key = t.solvency_II_regulatory_key
		 FROM EDW_Staging.assumed.OPENBOX_UW_Staging t
		WHERE t.EndDate='9999-12-31'
		UNION
		SELECT DISTINCT LineOfBusinessName = 'N/A'
			,solvency_II_regulatory_key = solII.solvency_II_regulatory_key
		FROM EDW_PREPROD.lloyds.TBL_CLAIM_LLYDS r
		LEFT JOIN (
				SELECT DISTINCT plcy_SRC = plcy_SRC
					,RPT_OFF_NAME = RPT_OFF_NAME
					,DIV_NAME = DIV_NAME
					,SUB_DEPT_CD = SUB_DEPT_CD
					,PRO_RATA_XOL_NAME = PRO_RATA_XOL_NAME
					,TRTY_FAC_NAME = TRTY_FAC_NAME
					,DEPT_NAME = DEPT_NAME
					,DEPT_CD = DEPT_CD
					,Contract_Reference = Contract_Reference
					,sub_dept_name = sub_dept_name
					,INCEPT_DT = INCEPT_DT
				FROM EDW_PREPROD.dbo.MAP_CONTRACT_EDW mce
				WHERE plcy_SRC = 'OPENBOX'
			) m
			ON M.Contract_Reference = r.policyNumber
		LEFT JOIN EDW_PREPROD.dbo.solvency_II_regulatory_etl solII
			ON solII.source = M.PLCY_SRC
				AND ISNULL(solII.branch_name, 'Uncoded') = ISNULL(M.RPT_OFF_NAME, 'Uncoded')
				AND ISNULL(solII.product_group_name, 'Uncoded') = ISNULL(M.DIV_NAME, 'Uncoded')
				AND ISNULL(solII.product_department_name, 'Uncoded') = ISNULL(M.DEPT_NAME, 'Uncoded')
				AND ISNULL(solII.product_department_code, 'Uncoded') = ISNULL(M.DEPT_CD, 'Uncoded')
				AND ISNULL(solII.lob_name, 'Uncoded') = ISNULL(M.SUB_DEPT_NAME, 'Uncoded')
				AND ISNULL(solII.lob_code, 'Uncoded') = ISNULL(M.SUB_DEPT_CD, 'Uncoded')
				AND ISNULL(solII.prorata_or_xol, 'Uncoded') = ISNULL(M.PRO_RATA_XOL_NAME, 'Uncoded')
				AND ISNULL(solII.treaty_or_fav, 'Uncoded') = ISNULL(M.TRTY_FAC_NAME, 'Uncoded')
				AND ISNULL(solII.property_or_casualty, 'Uncoded') = ISNULL(CASE WHEN M.DIV_NAME LIKE '%property%' THEN 'PROPERTY' WHEN M.DIV_NAME LIKE '%marine%' THEN 'PROPERTY' ELSE 'CASUALTY' END, 'Uncoded')
				AND solII.assumed_or_direct = 'assumed'
				AND COALESCE(solII.InceptionFrom, M.INCEPT_DT, '1 Jan 1900') <= COALESCE(M.INCEPT_DT, '1 Jan 1900')
				AND COALESCE(solII.InceptionTo, M.INCEPT_DT, '1 Jan 1900') >= COALESCE(M.INCEPT_DT, '1 Jan 1900')
		)
		--Underwriting piece of Code START
		UNION
		
		select distinct LOB_Name as LineOfBusinessName,solvency_II_regulatory_key
		from 
			EDW_PREPROD..RS_TIRS_UNDERWRITING_TOPSIDE with(nolock)
		union
		SELECT distinct  RTRIM(LTRIM(lob.desc_txt)) COLLATE Latin1_General_CI_AI	as LineOfBusinessName,
								solII.solvency_II_regulatory_key
							FROM  				
							src_tirs_db.dbo.acct_byline ab with(nolock)
							inner join  SRC_TIRS_DB.dbo.acct_doc ad with(nolock) on ab.doc_key = ad.doc_key
							left outer join SRC_TIRS_DB.dbo.xrf_lob_cds lob with(nolock) on lob.lob_cd = ab.pr_cls_cd
							left outer join EDW_PREPROD.dbo.solvency_II_regulatory_etl solII with(nolock) on	solII.source='TIRS' and 
							solII.assumed_or_direct = 'Assumed'
							and isnull(solII.lob_name,'')collate Latin1_General_CI_AI=	isnull(lob.desc_txt,'')
							where  ad.status_flg  = 'P'
		--Underwriting piece of Code END
		
		-- Adding LineOfBusinessCode
		ALTER TABLE #DimLineOfBusiness ADD LineOfBusinessCode VARCHAR(30) NULL
		
		UPDATE dlo
		SET LineOfBusinessCode = ISNULL(CAST(lob.lob_cd AS VARCHAR(30)), 'N/A')
		FROM #DimLineOfBusiness dlo
			LEFT JOIN SRC_TIRS_DB.dbo.xrf_lob_cds lob WITH(NOLOCK) ON RTRIM(LTRIM(lob.desc_txt)) COLLATE Latin1_General_CI_AI = dlo.LineOfBusinessName
		
		--NEW OPENBOX PART
		;WITH LOBSource AS (
				SELECT DISTINCT LineOfBusinessName = m.SUB_DEPT_NAME
					,LineOfBusinessCode = m.SUB_DEPT_CD
					,solvency_II_regulatory_key = s2re.solvency_II_regulatory_key
				FROM SRC_LLOYDS_DB.dbo.Policy p
				INNER JOIN SRC_LLOYDS_DB.dbo.PolicySection ps
					ON ps.lPolicyKey = p.lPolicyKey
					AND ps.lPolicyActivityKey = p.lActivePolicyActivityKey
				INNER JOIN SRC_LLOYDS_DB.dbo.PolicyActivity pa
					ON pa.lPolicyActivityKey = ps.lPolicyActivityKey
				INNER JOIN SRC_LLOYDS_DB.dbo.Typeofreportinglayer torl
					ON torl.lTypeOfReportingLayerKey = pa.lTypeOfReportingLayerKey
				INNER JOIN SRC_LLOYDS_DB.dbo.TypeOfProductgroup topg
					ON topg.lTypeOfProductGroupKey = torl.lTypeOfProductGroupKey
					AND topg.sCode = 'RI'
				LEFT JOIN (
						SELECT DISTINCT plcy_SRC = plcy_SRC
							,RPT_OFF_NAME = RPT_OFF_NAME
							,DIV_NAME = DIV_NAME
							,SUB_DEPT_CD = SUB_DEPT_CD
							,PRO_RATA_XOL_NAME = PRO_RATA_XOL_NAME
							,TRTY_FAC_NAME = TRTY_FAC_NAME
							,DEPT_NAME = DEPT_NAME
							,DEPT_CD = DEPT_CD
							,Contract_Reference = Contract_Reference
							,sub_dept_name = sub_dept_name
							,INCEPT_DT = INCEPT_DT
						FROM EDW_PREPROD.dbo.MAP_CONTRACT_EDW mce
						WHERE plcy_SRC = 'OPENBOX'
					) m
					ON m.Contract_Reference = p.sPolicyReference COLLATE DATABASE_DEFAULT
				LEFT JOIN EDW_PREPROD.dbo.solvency_II_regulatory_etl s2re
					ON s2re.source = M.PLCY_SRC
						AND ISNULL(s2re.branch_name, 'Uncoded') = ISNULL(m.RPT_OFF_NAME, 'Uncoded')
						AND ISNULL(s2re.product_group_name, 'Uncoded') = ISNULL(m.DIV_NAME, 'Uncoded')
						AND ISNULL(s2re.product_department_name, 'Uncoded') = ISNULL(m.DEPT_NAME, 'Uncoded')
						AND ISNULL(s2re.product_department_code, 'Uncoded') = ISNULL(m.DEPT_CD, 'Uncoded')
						AND ISNULL(s2re.lob_name, 'Uncoded') = ISNULL(m.SUB_DEPT_NAME, 'Uncoded')
						AND ISNULL(s2re.lob_code, 'Uncoded') = ISNULL(m.SUB_DEPT_CD, 'Uncoded')
						AND ISNULL(s2re.prorata_or_xol, 'Uncoded') = ISNULL(m.PRO_RATA_XOL_NAME, 'Uncoded')
						AND ISNULL(s2re.treaty_or_fav, 'Uncoded') = ISNULL(m.TRTY_FAC_NAME, 'Uncoded')
						AND ISNULL(s2re.property_or_casualty, 'Uncoded') = ISNULL(CASE WHEN M.DIV_NAME LIKE '%property%' THEN 'PROPERTY' WHEN m.DIV_NAME LIKE '%marine%' THEN 'PROPERTY' ELSE 'CASUALTY' END, 'Uncoded')
						AND s2re.assumed_or_direct = 'assumed'
						AND COALESCE(s2re.InceptionFrom, M.INCEPT_DT, '1 Jan 1900') <= COALESCE(m.INCEPT_DT, '1 Jan 1900')
						AND COALESCE(s2re.InceptionTo, M.INCEPT_DT, '1 Jan 1900') >= COALESCE(m.INCEPT_DT, '1 Jan 1900')
				WHERE m.SUB_DEPT_CD != '-9999'
			)
		MERGE INTO #DimLineOfBusiness t
		USING LOBSource s
			ON s.LineOfBusinessName = t.LineOfBusinessName
			AND COALESCE(s.solvency_II_regulatory_key, -9999) = COALESCE(t.solvency_II_regulatory_key, -9999)
		WHEN MATCHED THEN UPDATE
			SET LineOfBusinessCode = s.LineOfBusinessCode
		WHEN NOT MATCHED THEN INSERT
			(LineOfBusinessName
			,LineOfBusinessCode
			,solvency_II_regulatory_key
			)
		VALUES
			(s.LineOfBusinessName
			,s.LineOfBusinessCode
			,s.solvency_II_regulatory_key
			);

		-- Loading logic
		ALTER TABLE #DimLineOfBusiness ADD DataHash BINARY(20) NULL
		ALTER TABLE #DimLineOfBusiness ADD DataHashType1 BINARY(20) NULL
		
		UPDATE s
		SET DataHash = 0x0000000000000000000000000000000000000000,
			DataHashType1 = HASHBYTES('SHA1', s.LineOfBusinessCode)
		FROM #DimLineOfBusiness s

		-- check/enforce uniqueness on the dimension source data
		CREATE UNIQUE INDEX assumed_DimLineOfBusiness_UK ON #DimLineOfBusiness (LineOfBusinessName, solvency_II_regulatory_key)

		DROP TABLE IF EXISTS #LoadOperation

		CREATE TABLE #LoadOperation
		(LineOfBusinessName VARCHAR(255) COLLATE DATABASE_DEFAULT NOT NULL
		,solvency_II_regulatory_key INT NULL
		,Operation CHAR(1) NOT NULL
		,UNIQUE (LineOfBusinessName, solvency_II_regulatory_key)
		)

		INSERT INTO #LoadOperation
			(LineOfBusinessName
			,solvency_II_regulatory_key
			,Operation
			)
		SELECT LineOfBusinessName = COALESCE(t.LineOfBusinessName COLLATE DATABASE_DEFAULT, s.LineOfBusinessName COLLATE DATABASE_DEFAULT)
			,solvency_II_regulatory_key = COALESCE(t.solvency_II_regulatory_key, s.solvency_II_regulatory_key)
			,Operation = CASE WHEN t.DimLineOfBusinessID IS NULL THEN 'I' WHEN s.DataHash IS NULL THEN 'D' WHEN t.DataHash != s.DataHash AND t.DataHashType1 != s.DataHashType1 THEN 'U' WHEN t.DataHash != s.DataHash THEN '2' ELSE '1' END
		FROM (
			SELECT t.DimLineOfBusinessID, t.LineOfBusinessName, t.solvency_II_regulatory_key, t.DataHash,
					DataHashType1 = ISNULL(t.DataHashType1, 0x0000000000000000000000000000000000000000)
			FROM assumed.DimLineOfBusiness t
			WHERE t.EndDate = '31 Dec 9999'
			) t
		FULL JOIN #DimLineOfBusiness s
			ON s.LineOfBusinessName = t.LineOfBusinessName COLLATE DATABASE_DEFAULT
			AND COALESCE(s.solvency_II_regulatory_key, -1) = COALESCE(t.solvency_II_regulatory_key, -1)
		WHERE t.DataHash IS NULL
			OR s.DataHash IS NULL
			OR t.DataHash != s.DataHash
			OR t.DataHashType1 != s.DataHashType1

		BEGIN TRAN

		UPDATE t
		SET UpdateDate = p.NewStartDate
			,LineOfBusinessCode = s.LineOfBusinessCode
			,DataHashType1 = s.DataHashType1
		FROM assumed.DimLineOfBusiness t
		INNER JOIN #LoadOperation lo
			ON lo.LineOfBusinessName = t.LineOfBusinessName
			AND COALESCE(lo.solvency_II_regulatory_key, -1) = COALESCE(t.solvency_II_regulatory_key, -1)
			AND lo.Operation IN ('U', '1')
		INNER JOIN #DimLineOfBusiness s
			ON s.LineOfBusinessName = t.LineOfBusinessName COLLATE DATABASE_DEFAULT
			AND COALESCE(s.solvency_II_regulatory_key, -1) = COALESCE(t.solvency_II_regulatory_key, -1)
		CROSS JOIN #Parameters p
		WHERE p.NewStartDate BETWEEN t.StartDate AND t.EndDate

		UPDATE t
		SET EndDate = p.ClosingEndDate
		FROM assumed.DimLineOfBusiness t
		INNER JOIN #LoadOperation lo
			ON lo.LineOfBusinessName = t.LineOfBusinessName
			AND COALESCE(lo.solvency_II_regulatory_key, -1) = COALESCE(t.solvency_II_regulatory_key, -1)
			AND lo.Operation IN ('U', '2')
		CROSS JOIN #Parameters p
		WHERE t.EndDate = '31 Dec 9999'

		INSERT INTO assumed.DimLineOfBusiness
			(StartDate
			,UpdateDate
			,LineOfBusinessName
			,solvency_II_regulatory_key
			,LineOfBusinessCode
			,DataHash
			,DataHashType1
			)
		SELECT StartDate = p.NewStartDate
			,UpdateDate = p.NewStartDate
			,s.LineOfBusinessName
			,s.solvency_II_regulatory_key
			,s.LineOfBusinessCode
			,s.DataHash
			,s.DataHashType1
		FROM #DimLineOfBusiness s
		INNER JOIN #LoadOperation lo
			ON lo.LineOfBusinessName = s.LineOfBusinessName COLLATE DATABASE_DEFAULT
			AND COALESCE(lo.solvency_II_regulatory_key, -1) = COALESCE(s.solvency_II_regulatory_key, -1)
			AND lo.Operation IN ('I', 'U', '2')
		CROSS JOIN #Parameters p

		COMMIT

		DECLARE @ProcessName VARCHAR(100) = OBJECT_SCHEMA_NAME(@@PROCID) + '.' + OBJECT_NAME(@@PROCID)
		DECLARE @RowsProcessed BIGINT = COALESCE((SELECT COUNT(0) FROM #LoadOperation WHERE Operation IN ('I', 'U')), 0)
		DECLARE @LastIdentity BIGINT = SCOPE_IDENTITY()
		DECLARE @ProcessingStarted DATETIME = (SELECT p.NewStartDate FROM #Parameters p)
		DECLARE @ProcessingEnded DATETIME = GETDATE()
		DECLARE @SourceDataDate DATETIME = (SELECT [sql_date] FROM ETL.dbo.[day] WHERE today = 1)

		EXEC ETL.dbo.update_etl_controller @ps_process_name = @ProcessName
			,@pn_rows_processed = @RowsProcessed
			,@pdt_data_datetime = @SourceDataDate
			,@pdt_process_start_datetime = @ProcessingStarted
			,@pdt_process_end_datetime = @ProcessingEnded
			,@pn_error_number = 0
			,@ps_comment = NULL
			,@pn_max_processed_event_id = @LastIdentity
	END TRY
	BEGIN CATCH
		IF @@TRANCOUNT > 0
		BEGIN
			ROLLBACK
		END

		DECLARE @ErrorDescription VARCHAR(8000) = CONCAT('Error: ', ERROR_NUMBER(), ' - ', ERROR_MESSAGE(), '; ', 'Occurred in procedure: ' + ERROR_PROCEDURE() + ', ', 'Line ', ERROR_LINE())
		DECLARE @ErrorNumber INT = ERROR_NUMBER()
		DECLARE @ErrorMessage VARCHAR(8000) = ERROR_MESSAGE()
		DECLARE @ErrorSeverity INT = ERROR_SEVERITY()
		DECLARE @ErrorState INT = ERROR_STATE()
		DECLARE @ProcessNameC VARCHAR(100) = OBJECT_SCHEMA_NAME(@@PROCID) + '.' + OBJECT_NAME(@@PROCID)
		DECLARE @ProcessingStartedC DATETIME = (SELECT p.NewStartDate FROM #Parameters p)
		DECLARE @ProcessingEndedC DATETIME = GETDATE()
		DECLARE @SourceDataDateC DATETIME = (SELECT [sql_date] FROM ETL.dbo.[day] WHERE today = 1)

		EXEC ETL.dbo.update_etl_controller @ps_process_name = @ProcessNameC
			,@pn_rows_processed = 0
			,@pdt_data_datetime = @SourceDataDateC
			,@pdt_process_start_datetime = @ProcessingStartedC
			,@pdt_process_end_datetime = @ProcessingEndedC
			,@pn_error_number = @ErrorNumber
			,@ps_comment = @ErrorDescription
			,@pn_max_processed_event_id = 0

		EXEC ETL.dbo.insert_error_log @process_name = @ProcessNameC
			,@object_name = 0
			,@user_message = @ErrorDescription
			,@status = 0
			,@remedy = 'Contact EDW team'

		RAISERROR(@ErrorMessage, @ErrorSeverity, @ErrorState)
	END CATCH
END





